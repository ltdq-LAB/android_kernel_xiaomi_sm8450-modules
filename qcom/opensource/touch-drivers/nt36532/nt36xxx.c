/*******************************************************
Description:
	Novatek touchscreen work function.

return:
	n.a.
*******************************************************/
static irqreturn_t nvt_ts_work_func(int irq, void *data)
{
	int32_t ret = -1;
	uint8_t point_data[POINT_DATA_LEN + PEN_DATA_LEN + 1 + DUMMY_BYTES] = {0};
	uint32_t position = 0;
	uint32_t input_x = 0;
	uint32_t input_y = 0;
	uint32_t input_w = 0;
	uint32_t input_p = 0;
	uint8_t input_id = 0;
#if MT_PROTOCOL_B
	uint8_t press_id[TOUCH_MAX_FINGER_NUM] = {0};
#endif /* MT_PROTOCOL_B */
	int32_t i = 0;
	int32_t finger_cnt = 0;
	uint8_t pen_format_id = 0;
	uint32_t pen_x = 0;
	uint32_t pen_y = 0;
	uint32_t pen_pressure = 0;
	uint32_t pen_distance = 0;
	int8_t pen_tilt_x = 0;
	int8_t pen_tilt_y = 0;
	uint32_t pen_btn1 = 0;
	uint32_t pen_btn2 = 0;
	uint32_t pen_battery = 0;

	struct sched_param par = { .sched_priority = MAX_RT_PRIO - 1};

	if (!ts->irq_thread_boosted) {
		ts->irq_thread_boosted = true;
		sched_setscheduler_nocheck(current, SCHED_FIFO, &par);
	}

#if WAKEUP_GESTURE
	if (bTouchIsAwake == 0) {
		pm_wakeup_event(&ts->client->dev, 5000);
	}
#endif

	mutex_lock(&ts->lock);

	if (smp_load_acquire(&ts->dev_pm_suspend)) {
		ret = wait_for_completion_timeout(&ts->dev_pm_suspend_completion, msecs_to_jiffies(500));
		if (!ret) {
			NVT_ERR("system(spi) can't finished resuming procedure, skip it\n");
			goto XFER_ERROR;
		}
	}

#if NVT_SUPER_RESOLUTION_N
	ret = CTP_SPI_READ(ts->client, point_data, POINT_DATA_LEN + 1);
#else /* #if NVT_SUPER_RESOLUTION_N */
	if (ts->pen_support)
		ret = CTP_SPI_READ(ts->client, point_data, POINT_DATA_LEN + PEN_DATA_LEN + 1);
	else
		ret = CTP_SPI_READ(ts->client, point_data, POINT_DATA_LEN + 1);
#endif /* #if NVT_SUPER_RESOLUTION_N */
	if (ret < 0) {
		NVT_ERR("CTP_SPI_READ failed.(%d)\n", ret);
		goto XFER_ERROR;
	}
/*
	//--- dump SPI buf ---
	for (i = 0; i < 10; i++) {
		printk("%02X %02X %02X %02X %02X %02X  ",
			point_data[1+i*6], point_data[2+i*6], point_data[3+i*6], point_data[4+i*6], point_data[5+i*6], point_data[6+i*6]);
	}
	printk("\n");
*/

#if NVT_TOUCH_WDT_RECOVERY
	/* ESD protect by WDT */
	if (nvt_wdt_fw_recovery(point_data)) {
		NVT_ERR("Recover for fw reset, %02X\n", point_data[1]);
		if (point_data[1] == 0xFE) {
			nvt_sw_reset_idle();
		}
		nvt_read_fw_history(ts->mmap->MMAP_HISTORY_EVENT0);
		nvt_read_fw_history(ts->mmap->MMAP_HISTORY_EVENT1);
		release_touch_event();
		release_pen_event();
		if (nvt_get_dbgfw_status()) {
			if (nvt_update_firmware(DEFAULT_DEBUG_FW_NAME) < 0) {
				NVT_ERR("use built-in fw");
				nvt_update_firmware(ts->fw_name);
			}
		} else {
			nvt_update_firmware(ts->fw_name);
		}
		nvt_all_para_recovery();
		nvt_apply_host_modes_locked(true);
		goto XFER_ERROR;
	}
#endif /* #if NVT_TOUCH_WDT_RECOVERY */

	/* ESD protect by FW handshake */
	if (nvt_fw_recovery(point_data)) {
#if NVT_TOUCH_ESD_PROTECT
		nvt_esd_check_enable(true);
#endif /* #if NVT_TOUCH_ESD_PROTECT */
		goto XFER_ERROR;
	}

#if POINT_DATA_CHECKSUM
   if (POINT_DATA_LEN >= POINT_DATA_CHECKSUM_LEN) {
       ret = nvt_ts_point_data_checksum(point_data, POINT_DATA_CHECKSUM_LEN);
       if (ret) {
           goto XFER_ERROR;
       }
   }
#endif /* POINT_DATA_CHECKSUM */

#if WAKEUP_GESTURE
	if (bTouchIsAwake == 0) {
		input_id = (uint8_t)(point_data[1] >> 3);
		nvt_ts_wakeup_gesture_report(input_id, point_data);
		if (ts->pen_support) {
			pen_format_id = point_data[66];
			nvt_ts_pen_gesture_report(pen_format_id);
		}
		mutex_unlock(&ts->lock);
		return IRQ_HANDLED;
	}
#endif

	finger_cnt = 0;

	for (i = 0; i < ts->max_touch_num; i++) {
		position = 1 + 6 * i;
		input_id = (uint8_t)(point_data[position + 0] >> 3);
		if ((input_id == 0) || (input_id > ts->max_touch_num))
			continue;

		if (((point_data[position] & 0x07) == 0x01) || ((point_data[position] & 0x07) == 0x02)) {	//finger down (enter & moving)
#if NVT_TOUCH_ESD_PROTECT
			/* update interrupt timer */
			irq_timer = jiffies;
#endif /* #if NVT_TOUCH_ESD_PROTECT */
#if NVT_SUPER_RESOLUTION_N
			input_x = (uint32_t)(point_data[position + 1] << 8) + (uint32_t) (point_data[position + 2]);
			input_y = (uint32_t)(point_data[position + 3] << 8) + (uint32_t) (point_data[position + 4]);
			if ((input_x < 0) || (input_y < 0))
				continue;
			if ((input_x > ts->abs_x_max * NVT_SUPER_RESOLUTION_N - 1) || (input_y > ts->abs_y_max * NVT_SUPER_RESOLUTION_N - 1))
				continue;
			input_w = (uint32_t)(point_data[position + 5]);
			if (input_w == 0)
				input_w = 1;
			input_p = (uint32_t)(point_data[1 + 98 + i]);
			if (input_p == 0)
				input_p = 1;
#else /* #if NVT_SUPER_RESOLUTION_N */
			input_x = (uint32_t)(point_data[position + 1] << 4) + (uint32_t) (point_data[position + 3] >> 4);
			input_y = (uint32_t)(point_data[position + 2] << 4) + (uint32_t) (point_data[position + 3] & 0x0F);
			if ((input_x < 0) || (input_y < 0))
				continue;
			if ((input_x > ts->abs_x_max - 1) || (input_y > ts->abs_y_max - 1))
				continue;
			input_w = (uint32_t)(point_data[position + 4]);
			if (input_w == 0)
				input_w = 1;
			if (i < 2) {
				input_p = (uint32_t)(point_data[position + 5]) + (uint32_t)(point_data[i + 63] << 8);
				if (input_p > TOUCH_FORCE_NUM)
					input_p = TOUCH_FORCE_NUM;
			} else {
				input_p = (uint32_t)(point_data[position + 5]);
			}
			if (input_p == 0)
				input_p = 1;
#endif /* #if NVT_SUPER_RESOLUTION_N */

#if MT_PROTOCOL_B
			press_id[input_id - 1] = 1;
			input_mt_slot(ts->input_dev, input_id - 1);
			input_mt_report_slot_state(ts->input_dev, MT_TOOL_FINGER, true);
#else /* MT_PROTOCOL_B */
			input_report_abs(ts->input_dev, ABS_MT_TRACKING_ID, input_id - 1);
			input_report_key(ts->input_dev, BTN_TOUCH, 1);
#endif /* MT_PROTOCOL_B */

			input_report_abs(ts->input_dev, ABS_MT_POSITION_X, input_x);
			input_report_abs(ts->input_dev, ABS_MT_POSITION_Y, input_y);
			if (TOUCH_MAJOR_MAX_VALUE == input_w) {
				input_w = TOUCH_MAJOR_MAX_VALUE + 1;
				NVT_LOG("palm event detected");
			}
			input_report_abs(ts->input_dev, ABS_MT_TOUCH_MAJOR, input_w);
			input_report_abs(ts->input_dev, ABS_MT_PRESSURE, input_p);

#if MT_PROTOCOL_B
#else /* MT_PROTOCOL_B */
			input_mt_sync(ts->input_dev);
#endif /* MT_PROTOCOL_B */

			finger_cnt++;
		}
	}

#if MT_PROTOCOL_B
	for (i = 0; i < ts->max_touch_num; i++) {
		if (press_id[i] != 1) {
			input_mt_slot(ts->input_dev, i);
			input_report_abs(ts->input_dev, ABS_MT_TOUCH_MAJOR, 0);
			input_report_abs(ts->input_dev, ABS_MT_PRESSURE, 0);
			input_mt_report_slot_state(ts->input_dev, MT_TOOL_FINGER, false);
		}
	}

	input_report_key(ts->input_dev, BTN_TOUCH, (finger_cnt > 0));
#else /* MT_PROTOCOL_B */
	if (finger_cnt == 0) {
		input_report_key(ts->input_dev, BTN_TOUCH, 0);
		input_mt_sync(ts->input_dev);
	}
#endif /* MT_PROTOCOL_B */

#if TOUCH_KEY_NUM > 0
	if (point_data[61] == 0xF8) {
#if NVT_TOUCH_ESD_PROTECT
		/* update interrupt timer */
		irq_timer = jiffies;
#endif /* #if NVT_TOUCH_ESD_PROTECT */
		for (i = 0; i < ts->max_button_num; i++) {
			input_report_key(ts->input_dev, touch_key_array[i], ((point_data[62] >> i) & 0x01));
		}
	} else {
		for (i = 0; i < ts->max_button_num; i++) {
			input_report_key(ts->input_dev, touch_key_array[i], 0);
		}
	}
#endif

	input_sync(ts->input_dev);

	if (ts->pen_support) {
/*
		//--- dump pen buf ---
		printk("%02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X\n",
			point_data[66], point_data[67], point_data[68], point_data[69], point_data[70],
			point_data[71], point_data[72], point_data[73], point_data[74], point_data[75],
			point_data[76], point_data[77], point_data[78], point_data[79]);
*/
#if CHECK_PEN_DATA_CHECKSUM
		if (nvt_ts_pen_data_checksum(&point_data[66], PEN_DATA_LEN)) {
			// pen data packet checksum not match, skip it
			goto XFER_ERROR;
		}
#endif // #if CHECK_PEN_DATA_CHECKSUM

		// parse and handle pen report
		pen_format_id = point_data[66];
		if (pen_format_id != 0xFF) {
			if (pen_format_id == 0x01) {
				// report pen data
				pen_x = (uint32_t)(point_data[67] << 8) + (uint32_t)(point_data[68]);
				pen_y = (uint32_t)(point_data[69] << 8) + (uint32_t)(point_data[70]);
				pen_pressure = (uint32_t)(point_data[71] << 8) + (uint32_t)(point_data[72]);
				pen_tilt_x = (int32_t)point_data[73];
				pen_tilt_y = (int32_t)point_data[74];
				pen_distance = (uint32_t)(point_data[75] << 8) + (uint32_t)(point_data[76]);
				pen_btn1 = (uint32_t)(point_data[77] & 0x01);
				pen_btn2 = (uint32_t)((point_data[77] >> 1) & 0x01);
				pen_battery = (uint32_t)point_data[78];
//				printk("x=%d,y=%d,p=%d,tx=%d,ty=%d,d=%d,b1=%d,b2=%d,bat=%d\n", pen_x, pen_y, pen_pressure,
//						pen_tilt_x, pen_tilt_y, pen_distance, pen_btn1, pen_btn2, pen_battery);

				input_report_abs(ts->pen_input_dev, ABS_X, pen_x);
				input_report_abs(ts->pen_input_dev, ABS_Y, pen_y);
				input_report_abs(ts->pen_input_dev, ABS_PRESSURE, pen_pressure);
				input_report_key(ts->pen_input_dev, BTN_TOUCH, !!pen_pressure);
				input_report_abs(ts->pen_input_dev, ABS_TILT_X, pen_tilt_x);
				input_report_abs(ts->pen_input_dev, ABS_TILT_Y, pen_tilt_y);
				input_report_abs(ts->pen_input_dev, ABS_DISTANCE, pen_distance);
				input_report_key(ts->pen_input_dev, BTN_TOOL_PEN, !!pen_distance || !!pen_pressure);
				input_report_key(ts->pen_input_dev, BTN_STYLUS, pen_btn1);
				input_report_key(ts->pen_input_dev, BTN_STYLUS2, pen_btn2);
				// TBD: pen battery event report
				// NVT_LOG("pen_battery=%d\n", pen_battery);
			} else if (pen_format_id == 0xF0) {
				// report Pen ID
			} else {
				NVT_ERR("Unknown pen format id!\n");
				goto XFER_ERROR;
			}
		} else { // pen_format_id = 0xFF, i.e. no pen present
			input_report_abs(ts->pen_input_dev, ABS_X, 0);
			input_report_abs(ts->pen_input_dev, ABS_Y, 0);
			input_report_abs(ts->pen_input_dev, ABS_PRESSURE, 0);
			input_report_abs(ts->pen_input_dev, ABS_TILT_X, 0);
			input_report_abs(ts->pen_input_dev, ABS_TILT_Y, 0);
			input_report_abs(ts->pen_input_dev, ABS_DISTANCE, 0);
			input_report_key(ts->pen_input_dev, BTN_TOUCH, 0);
			input_report_key(ts->pen_input_dev, BTN_TOOL_PEN, 0);
			input_report_key(ts->pen_input_dev, BTN_STYLUS, 0);
			input_report_key(ts->pen_input_dev, BTN_STYLUS2, 0);
		}

		input_sync(ts->pen_input_dev);
	} /* if (ts->pen_support) */

XFER_ERROR:

	mutex_unlock(&ts->lock);
	return IRQ_HANDLED;
}


/*******************************************************
Description:
	Novatek touchscreen check chip version trim function.

return:
	Executive outcomes. 0---NVT IC. -1---not NVT IC.
*******************************************************/
static int32_t nvt_ts_check_chip_ver_trim(struct nvt_ts_hw_reg_addr_info hw_regs)
{
	uint8_t buf[8] = {0};
	int32_t retry = 0;
	int32_t list = 0;
	int32_t i = 0;
	int32_t found_nvt_chip = 0;
	int32_t ret = -1;
	uint8_t enb_casc = 0;

	/* hw reg mapping */
	ts->chip_ver_trim_addr = hw_regs.chip_ver_trim_addr;
	ts->swrst_sif_addr = hw_regs.swrst_sif_addr;
	ts->crc_err_flag_addr = hw_regs.crc_err_flag_addr;

	NVT_LOG("check chip ver trim with chip_ver_trim_addr=0x%06x, "
			"swrst_sif_addr=0x%06x, crc_err_flag_addr=0x%06x\n",
			ts->chip_ver_trim_addr, ts->swrst_sif_addr, ts->crc_err_flag_addr);

	//---Check for 5 times---
	for (retry = 5; retry > 0; retry--) {

		nvt_bootloader_reset();

		nvt_set_page(ts->chip_ver_trim_addr);

		buf[0] = ts->chip_ver_trim_addr & 0x7F;
		buf[1] = 0x00;
		buf[2] = 0x00;
		buf[3] = 0x00;
		buf[4] = 0x00;
		buf[5] = 0x00;
		buf[6] = 0x00;
		CTP_SPI_WRITE(ts->client, buf, 7);

		buf[0] = ts->chip_ver_trim_addr & 0x7F;
		buf[1] = 0x00;
		buf[2] = 0x00;
		buf[3] = 0x00;
		buf[4] = 0x00;
		buf[5] = 0x00;
		buf[6] = 0x00;
		CTP_SPI_READ(ts->client, buf, 7);
		NVT_LOG("buf[1]=0x%02X, buf[2]=0x%02X, buf[3]=0x%02X, buf[4]=0x%02X, buf[5]=0x%02X, buf[6]=0x%02X\n",
			buf[1], buf[2], buf[3], buf[4], buf[5], buf[6]);

		// compare read chip id on supported list
		for (list = 0; list < (sizeof(trim_id_table) / sizeof(struct nvt_ts_trim_id_table)); list++) {
			found_nvt_chip = 0;

			// compare each byte
			for (i = 0; i < NVT_ID_BYTE_MAX; i++) {
				if (trim_id_table[list].mask[i]) {
					if (buf[i + 1] != trim_id_table[list].id[i])
						break;
				}
			}

			if (i == NVT_ID_BYTE_MAX) {
				found_nvt_chip = 1;
			}

			if (found_nvt_chip) {
				NVT_LOG("This is NVT touch IC\n");
				if (trim_id_table[list].mmap->ENB_CASC_REG.addr) {
					/* check single or cascade */
					nvt_read_reg(trim_id_table[list].mmap->ENB_CASC_REG, &enb_casc);
					/* NVT_LOG("ENB_CASC=0x%02X\n", enb_casc); */
					if (enb_casc & 0x01) {
						NVT_LOG("Single Chip\n");
						ts->mmap = trim_id_table[list].mmap;
					} else {
						NVT_LOG("Cascade Chip\n");
						ts->mmap = trim_id_table[list].mmap_casc;
					}
				} else {
					/* for chip that do not have ENB_CASC */
					ts->mmap = trim_id_table[list].mmap;
				}
				ts->hw_crc = trim_id_table[list].hwinfo->hw_crc;
				ts->auto_copy = trim_id_table[list].hwinfo->auto_copy;

				/* hw reg re-mapping */
				ts->chip_ver_trim_addr = trim_id_table[list].hwinfo->hw_regs->chip_ver_trim_addr;
				ts->swrst_sif_addr = trim_id_table[list].hwinfo->hw_regs->swrst_sif_addr;
				ts->crc_err_flag_addr = trim_id_table[list].hwinfo->hw_regs->crc_err_flag_addr;

				NVT_LOG("set reg chip_ver_trim_addr=0x%06x, "
						"swrst_sif_addr=0x%06x, crc_err_flag_addr=0x%06x\n",
						ts->chip_ver_trim_addr, ts->swrst_sif_addr, ts->crc_err_flag_addr);

				ret = 0;
				goto out;
			} else {
				ts->mmap = NULL;
				ret = -1;
			}
		}

		msleep(10);
	}

out:
	return ret;
}

/*******************************************************
Description:
	Novatek touchscreen check chip version trim loop
	function. Check chip version trim via hw regs table.

return:
	Executive outcomes. 0---NVT IC. -1---not NVT IC.
*******************************************************/
static int32_t nvt_ts_check_chip_ver_trim_loop(void) {
    uint8_t i = 0;
	int32_t ret = 0;

	struct nvt_ts_hw_reg_addr_info hw_regs_table[] = {
		hw_reg_addr_info,
		hw_reg_addr_info_old_w_isp,
		hw_reg_addr_info_legacy_w_isp
	};

    for (i = 0; i < (sizeof(hw_regs_table) / sizeof(struct nvt_ts_hw_reg_addr_info)); i++) {
        //---check chip version trim---
        ret = nvt_ts_check_chip_ver_trim(hw_regs_table[i]);
		if (!ret) {
			break;
		}
    }

	return ret;
}

static int nvt_ts_check_dt(struct device_node *np)
{
	int i;
	int count;
	int ret = -ENODEV;
	struct device_node *node = NULL;
	struct drm_panel *panel = NULL;

	active_panel = NULL;
	if (!np)
		return -EINVAL;

	count = of_count_phandle_with_args(np, "panel", NULL);
	if (count <= 0)
		return count < 0 ? count : -ENODEV;

	for (i = 0; i < count; i++) {
		node = of_parse_phandle(np, "panel", i);
		if (!node) {
			ret = -EINVAL;
			continue;
		}
		panel = of_drm_find_panel(node);
		of_node_put(node);
		if (!IS_ERR(panel)) {
			active_panel = panel;
			return 0;
		}
		ret = PTR_ERR(panel);
	}

	return ret;
}


static void nvt_set_gesture_mode_locked(struct nvt_ts_data *nvt,
					int gesture_command)
{
	NVT_LOG("%s wake gestures (mask=0x%x)\n",
		gesture_command ? "enable" : "disable", gesture_command);

	if (nvt->ic_state < NVT_IC_RESUME_OUT) {
		nvt->gesture_command_delayed = gesture_command;
		NVT_LOG("IC transition state %d; defer gesture mask 0x%x\n",
			nvt->ic_state, gesture_command);
		return;
	}

	nvt->gesture_command = gesture_command;
	nvt_panel_doubleclick_enable(nvt, !!gesture_command);
}

static int nvt_requested_gesture_command_locked(struct nvt_ts_data *nvt)
{
	if (nvt->gesture_command_delayed >= 0)
		return nvt->gesture_command_delayed;

	return nvt->gesture_command;
}

static void nvt_update_pen_shorthand_locked(struct nvt_ts_data *nvt)
{
	int gesture_mask = nvt_requested_gesture_command_locked(nvt);
	bool enable = nvt->pen_shorthand_enabled &&
		      nvt->pen_bluetooth_connect;

	if (enable)
		gesture_mask |= BIT(1);
	else
		gesture_mask &= ~BIT(1);

	nvt_set_gesture_mode_locked(nvt, gesture_mask);
}

static int nvt_set_stylus_connection_locked(struct nvt_ts_data *nvt, int value)
{
	bool connected;
	int type;
	int ret;

	if (!nvt->pen_support)
		return -EOPNOTSUPP;

	if (value == TOUCH_STYLUS_CONNECTION_RESET) {
		nvt->pen_count = 0;
	} else {
		if (value < 0 ||
		    value > TOUCH_STYLUS_CONNECTION_CONNECTED +
			    TOUCH_STYLUS_TYPE_LIUQIN_SUPPORTED_M81P ||
		    (value & ~(TOUCH_STYLUS_CONNECTION_CONNECTED |
			       TOUCH_STYLUS_CONNECTION_TYPE_MASK)))
			return -EINVAL;

		connected = !!(value & TOUCH_STYLUS_CONNECTION_CONNECTED);
		type = value & TOUCH_STYLUS_CONNECTION_TYPE_MASK;
		switch (type) {
		case TOUCH_STYLUS_TYPE_LIUQIN_LEGACY_K81P:
			nvt->pen_shield_flag = connected;
			break;
		case TOUCH_STYLUS_TYPE_LIUQIN_SUPPORTED_M81P:
			if (connected)
				nvt->pen_count++;
			else
				nvt->pen_count--;
			break;
		default:
			/*
			 * Exact liuqin DATA_MODE_20 accepts clamped values 0 and
			 * 3..16 without changing the counters, but still executes
			 * the common release/status-update tail below.
			 */
			break;
		}
	}

	nvt->pen_bluetooth_connect = !nvt->pen_shield_flag &&
					       nvt->pen_count != 0;
	NVT_LOG("stylus event=0x%x supported=%d legacy=%d connected=%d\n",
		value, nvt->pen_count, nvt->pen_shield_flag,
		nvt->pen_bluetooth_connect);

	nvt_update_pen_shorthand_locked(nvt);
	nvt->host_mode_retry_count = 0;
	ret = nvt_apply_host_modes_locked(false);
	if (ret < 0)
		NVT_ERR("stylus state accepted but host-mode update is deferred\n");
	release_pen_event();

	/* The connection event is committed; userspace must not retry it. */
	return 0;
}

static int nvt_set_mode_value(void *private, enum touch_mode mode, int value)
{
	struct nvt_ts_data *nvt = private;
	int gesture_mask;
	int ret = 0;

	if (!nvt || READ_ONCE(nvt->teardown_in_progress))
		return -ENODEV;

	mutex_lock(&nvt->lock);
	if (READ_ONCE(nvt->teardown_in_progress)) {
		ret = -ENODEV;
		goto out_unlock;
	}

	gesture_mask = nvt_requested_gesture_command_locked(nvt);

	switch (mode) {
	case TOUCH_MODE_DOUBLETAP_GESTURE:
		if (value != 0 && value != 1) {
			ret = -EINVAL;
			goto out_unlock;
		}
		if (value)
			gesture_mask |= BIT(0);
		else
			gesture_mask &= ~BIT(0);
		break;
	case TOUCH_MODE_SINGLETAP_GESTURE:
		if (value != 0 && value != 1) {
			ret = -EINVAL;
			goto out_unlock;
		}
		nvt->pen_shorthand_enabled = value;
		nvt_update_pen_shorthand_locked(nvt);
		goto out_unlock;
	case TOUCH_MODE_REPORT_RATE:
		if (value != 0 && value != 1) {
			ret = -EINVAL;
			goto out_unlock;
		}
		nvt->report_rate_enabled = value;
		nvt->host_mode_retry_count = 0;
		ret = nvt_apply_host_modes_locked(false);
		goto out_unlock;
	case TOUCH_MODE_STYLUS_CONNECTION:
		ret = nvt_set_stylus_connection_locked(nvt, value);
		goto out_unlock;
	case TOUCH_MODE_PEN_DETACH_GESTURE:
		if (value != 0 && value != 1) {
			ret = -EINVAL;
			goto out_unlock;
		}
		nvt->pen_detach_gesture_enabled = value;
		if (!value)
			atomic_set(&nvt->pen_detach_pending, 0);
		goto out_unlock;
	default:
		NVT_LOG("touch mode %d is not supported\n", mode);
		ret = -EOPNOTSUPP;
		goto out_unlock;
	}

	nvt_set_gesture_mode_locked(nvt, gesture_mask);

out_unlock:
	mutex_unlock(&nvt->lock);
	return ret;
}

static int nvt_get_mode_value(void *private, enum touch_mode mode)
{
	struct nvt_ts_data *nvt = private;
	int gesture_command;
	int value;

	if (!nvt || READ_ONCE(nvt->teardown_in_progress))
		return -ENODEV;

	mutex_lock(&nvt->lock);
	if (READ_ONCE(nvt->teardown_in_progress)) {
		value = -ENODEV;
		goto out_unlock;
	}
	gesture_command = nvt_requested_gesture_command_locked(nvt);

	switch (mode) {
	case TOUCH_MODE_DOUBLETAP_GESTURE:
		value = !!(gesture_command & BIT(0));
		break;
	case TOUCH_MODE_SINGLETAP_GESTURE:
		value = nvt->pen_shorthand_enabled;
		break;
	case TOUCH_MODE_REPORT_RATE:
		value = nvt->report_rate_enabled;
		break;
	case TOUCH_MODE_STYLUS_CONNECTION:
		/* This mode carries edge-triggered SET events, not state. */
		value = -EOPNOTSUPP;
		break;
	case TOUCH_MODE_PEN_DETACH_GESTURE:
		value = nvt->pen_detach_gesture_enabled;
		break;
	default:
		value = -EOPNOTSUPP;
		break;
	}

out_unlock:
	mutex_unlock(&nvt->lock);

	return value;
}

