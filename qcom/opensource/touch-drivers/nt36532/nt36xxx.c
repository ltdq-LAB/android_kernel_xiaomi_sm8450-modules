{
#if NVT_TOUCH_MP
	nvt_mp_proc_deinit();
#endif
#if NVT_TOUCH_EXT_PROC
	nvt_extra_proc_deinit();
#endif
#if NVT_TOUCH_PROC
	nvt_flash_proc_deinit();
#endif
}

static void nvt_destroy_workqueues(void)
{
#if defined(NVT_PEN_CONNECT_STRATEGY)
	cancel_work_sync(&ts->pen_charge_state_change_work);
	cancel_delayed_work_sync(&ts->host_mode_retry_work);
#endif

#if NVT_TOUCH_ESD_PROTECT
	if (nvt_esd_check_wq) {
		cancel_delayed_work_sync(&nvt_esd_check_work);
		nvt_esd_check_enable(false);
		destroy_workqueue(nvt_esd_check_wq);
		nvt_esd_check_wq = NULL;
	}
#endif

#if BOOT_UPDATE_FIRMWARE
	if (nvt_fwu_wq) {
		cancel_delayed_work_sync(&ts->nvt_fwu_work);
		destroy_workqueue(nvt_fwu_wq);
		nvt_fwu_wq = NULL;
	}
#endif

	if (nvt_lockdown_wq) {
		cancel_delayed_work_sync(&ts->nvt_lockdown_work);
		destroy_workqueue(nvt_lockdown_wq);
		nvt_lockdown_wq = NULL;
	}

	if (ts->event_wq) {
		destroy_workqueue(ts->event_wq);
		ts->event_wq = NULL;
	}

}

/*******************************************************
Description:
	Novatek touchscreen driver release function.

return:
	Executive outcomes. 0---succeed.
*******************************************************/
static int32_t nvt_ts_remove(struct spi_device *client)
{
	NVT_LOG("Removing driver...\n");
	if (!ts)
		return 0;

	WRITE_ONCE(ts->teardown_in_progress, true);
	bTouchIsAwake = 0;
	nvt_irq_enable(false);
	nvt_irq_wake_disable();

#ifdef CONFIG_TOUCHSCREEN_NVT_DEBUG_FS
	debugfs_remove_recursive(ts->debugfs);
	ts->debugfs = NULL;
#endif

	nvt_unregister_external_clients();
	nvt_remove_proc_entries();
	nvt_destroy_workqueues();
	nvt_wait_for_transition(ts);
#if defined(NVT_PEN_CONNECT_STRATEGY)
	update_pen_connect_strategy_value(false);
#endif
#if BOOT_UPDATE_FIRMWARE
	nvt_fw_update_deinit();
#endif

#if WAKEUP_GESTURE
	device_init_wakeup(&ts->client->dev, 0);
#endif

	if (client->irq > 0)
		free_irq(client->irq, ts);

#if defined(NVT_PEN_CONNECT_STRATEGY)
	mutex_destroy(&ts->pen_switch_lock);
#endif
	mutex_destroy(&ts->power_supply_lock);
	mutex_destroy(&ts->irq_lock);
	mutex_destroy(&ts->xbuf_lock);
	mutex_destroy(&ts->transition_lock);
	mutex_destroy(&ts->lock);

	nvt_gpio_deconfig(ts);

	if (ts->pen_input_dev) {
		input_unregister_device(ts->pen_input_dev);
		ts->pen_input_dev = NULL;
	}

	if (ts->input_dev) {
		input_unregister_device(ts->input_dev);
		ts->input_dev = NULL;
	}

	spi_set_drvdata(client, NULL);
	active_panel = NULL;

	kfree(ts->rbuf);
	ts->rbuf = NULL;
	kfree(ts->xbuf);
	ts->xbuf = NULL;
	kfree(ts);
	ts = NULL;

	return 0;
}

