int nvt_read_lockdown_info(u8 *lockdown_info)
{
	size_t size = 0;
	void *smem;

	if (!lockdown_info)
		return -EINVAL;

	smem = qcom_smem_get(QCOM_SMEM_HOST_ANY, NVT_LOCKDOWN_SMEM_ID,
			     &size);
	if (IS_ERR(smem))
		return PTR_ERR(smem);
	if (size < NVT_LOCKDOWN_SIZE)
		return -EMSGSIZE;

	memcpy(lockdown_info, smem, NVT_LOCKDOWN_SIZE);
	return 0;
}

